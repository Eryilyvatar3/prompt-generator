"""
Модуль генерации промптов для LLM (v2).
Отличие от v1:
- явное требование покрытия КАЖДОГО входного требования;
- таблица трассируемости «требование → тест-кейс»;
- унифицированные приоритеты High/Medium/Low;
- расширенный обязательный минимум тест-кейсов;
- запрет «выдуманных» дефектов в QA Report.
"""


class PromptGenerator:
    """Генератор промптов для тестовой документации (v2)."""

    def __init__(self, requirements: str):
        if not requirements or not requirements.strip():
            raise ValueError("Требования не могут быть пустыми")
        self.requirements = requirements.strip()

    def build_prompt(self) -> str:
        return f"""Ты — опытный QA Lead и тест-аналитик. На основе предоставленных требований сгенерируй полный пакет тестовой документации.

### ВХОДНЫЕ ТРЕБОВАНИЯ:
{self.requirements}

### ОБЩИЕ ПРАВИЛА (обязательны к соблюдению):
1. КАЖДОЕ входное требование должно быть покрыто минимум одним тест-кейсом. Пропуск требования — критическая ошибка.
2. Приоритеты тест-кейсов указывай ТОЛЬКО значениями: High | Medium | Low (на английском, без сокращений).
3. Не выдумывай дефекты, которые не вытекают из тест-кейсов. QA Report должен ссылаться на ID конкретных тест-кейсов.
4. Используй только Markdown. Не добавляй пояснений до или после документов.

### ЗАДАЧА:
Сгенерируй четыре документа строго в указанном порядке:

1. **TEST PLAN**
   - Цель тестирования
   - Объект тестирования
   - Стратегия (функциональное, регрессионное, негативное тестирование)
   - Критерии входа и выхода
   - Тестовое окружение и тестовые данные
   - Риски и способы их митигации

2. **CHECKLIST**
   - Не более 15 пунктов в формате `[ ]`
   - Сгруппируй по модулям (Добавление, Отображение, Изменение, Удаление, Валидация, Граничные значения)
   - Каждый пункт должен соответствовать хотя бы одному входному требованию

3. **TEST CASES**
   - Минимум 8 детальных тест-кейсов в формате Markdown-таблицы
   - Колонки: `ID | Название | Тип (Positive/Negative/Boundary) | Предусловие | Шаги | Ожидаемый результат | Приоритет`
   - Обязательно должны присутствовать:
     * добавление товара СО СТРАНИЦЫ КАТАЛОГА (Positive)
     * добавление товара С КАРТОЧКИ ТОВАРА (Positive)
     * отображение цены за единицу и общей стоимости в корзине (Positive)
     * изменение количества в допустимом диапазоне 1–10 (Boundary)
     * попытка установить количество меньше 1 или больше 10 (Negative/Boundary)
     * удаление товара с пересчётом итоговой суммы (Positive)
     * добавление товара, отсутствующего на складе (Negative)
     * превышение лимита 20 уникальных товаров (Negative/Boundary)
   - После таблицы добавь подраздел **Трассируемость** — таблица `Требование № | ID тест-кейсов`, покрывающая все входные требования.

4. **QA REPORT**
   - Смоделируй отчёт о тестировании на основе сгенерированных тест-кейсов
   - Укажи: Всего тестов, Пройдено, Провалено
   - Опиши 2–3 дефекта, каждый — со ссылкой на ID тест-кейса (например: «TC-07: при превышении лимита 20 товаров сообщение не выводится»)
   - Сделай вывод о готовности к релизу

### ФОРМАТ ВЫВОДА:
Начни каждый документ с заголовка второго уровня:
## TEST PLAN
## CHECKLIST
## TEST CASES
## QA REPORT
"""