"""
Модуль генерации промптов для LLM.
Принимает требования и формирует структурированный промпт
для генерации тестовой документации: test plan, checklist,
test cases, QA report.
"""


class PromptGenerator:
    """Генератор промптов для тестовой документации."""

    def __init__(self, requirements: str):
        if not requirements or not requirements.strip():
            raise ValueError("Требования не могут быть пустыми")
        self.requirements = requirements.strip()

    def build_prompt(self) -> str:
        """
        Собирает итоговый промпт для LLM на основе требований.

        Returns:
            str: Готовый промпт.
        """
        return f"""Ты — опытный QA Lead и тест-аналитик. Твоя задача — на основе предоставленных требований сгенерировать полный пакет тестовой документации.

### ВХОДНЫЕ ТРЕБОВАНИЯ:
{self.requirements}

### ЗАДАЧА:
Сгенерируй четыре документа строго в указанном порядке и формате:

1. **TEST PLAN**
   - Цель тестирования
   - Объект тестирования
   - Стратегия (функциональное, регрессионное, негативное тестирование)
   - Критерии входа и выхода
   - Тестовое окружение и тестовые данные

2. **CHECKLIST**
   - Краткий список проверок (не более 15 пунктов) в формате чек-листа с чекбоксами [ ]
   - Сгруппируй по модулям (например: Добавление, Изменение, Удаление, Валидация)

3. **TEST CASES**
   - Минимум 5 детальных тест-кейсов в формате Markdown-таблицы
   - Колонки: ID | Название | Предусловие | Шаги | Ожидаемый результат | Приоритет
   - Обязательно включи:
     * позитивный сценарий (Happy Path),
     * граничные значения (например, минимальное и максимальное количество),
     * негативный сценарий (например, товара нет на складе)

4. **QA REPORT**
   - Смоделируй гипотетический отчёт о тестировании (представь, что ты провёл тестирование по этим кейсам)
   - Укажи: Всего тестов, Пройдено, Провалено
   - Опиши 2-3 найденных дефекта, связанных с логикой работы
   - Сделай вывод о готовности к релизу

### ФОРМАТ ВЫВОДА:
Используй Markdown. Каждый документ начинай с заголовка второго уровня:
## TEST PLAN
## CHECKLIST
## TEST CASES
## QA REPORT

Не добавляй никаких пояснений до или после документов. Только четыре документа в указанном порядке.
"""